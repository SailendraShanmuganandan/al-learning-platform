import type { QuestionSource } from '../types';
import { Sparkles, PenTool } from 'lucide-react';

interface SourceBadgeProps {
  source: QuestionSource | string;
  size?: 'sm' | 'md';
}

export function SourceBadge({ source, size = 'sm' }: SourceBadgeProps) {
  const s = String(source).toUpperCase();
  const pad = size === 'sm' ? 'px-2 py-0.5 text-[10px]' : 'px-2.5 py-1 text-xs';

  if (s === 'AI') {
    return (
      <span
        title="Generated by AI"
        className={`inline-flex items-center gap-1 font-semibold rounded-full border bg-purple-500/10 text-purple-700 dark:text-purple-300 border-purple-500/20 ${pad}`}
      >
        <Sparkles size={size === 'sm' ? 10 : 12} />
        <span>AI</span>
      </span>
    );
  }

  return (
    <span
      title="Manually authored"
      className={`inline-flex items-center gap-1 font-medium rounded-full border bg-muted text-muted-foreground border-border ${pad}`}
    >
      <PenTool size={size === 'sm' ? 10 : 12} />
      <span>Manual</span>
    </span>
  );
}
