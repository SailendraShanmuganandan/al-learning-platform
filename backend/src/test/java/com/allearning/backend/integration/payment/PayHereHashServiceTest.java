package com.allearning.backend.integration.payment;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;

class PayHereHashServiceTest {

    private final PayHereHashService hashService = new PayHereHashService();

    @Test
    @DisplayName("Amount formatting: always 2 decimal places with '.' and no separators")
    void testFormatAmount() {
        assertEquals("2450.00", hashService.formatAmount(new BigDecimal("2450")));
        assertEquals("2450.50", hashService.formatAmount(new BigDecimal("2450.5")));
        assertEquals("2450.75", hashService.formatAmount(new BigDecimal("2450.75")));
        assertEquals("1000000.00", hashService.formatAmount(new BigDecimal("1000000")));
        assertEquals("0.00", hashService.formatAmount(BigDecimal.ZERO));
        assertEquals("0.00", hashService.formatAmount(null));
    }

    @Test
    @DisplayName("MD5 hex hashing: returns correct uppercase digest for known input")
    void testMd5Hex() {
        // MD5 of "test" is 098f6bcd4621d373cade4e832627b4f6 -> uppercase 098F6BCD4621D373CADE4E832627B4F6
        assertEquals("098F6BCD4621D373CADE4E832627B4F6", hashService.md5Hex("test"));
        // MD5 of empty string is d41d8cd98f00b204e9800998ecf8427e -> D41D8CD98F00B204E9800998ECF8427E
        assertEquals("D41D8CD98F00B204E9800998ECF8427E", hashService.md5Hex(""));
    }

    @Test
        @DisplayName("Checkout hash matches the fixed PayHere documentation vector")
    void testGenerateCheckoutHashKnownValues() {
        String merchantId = "1211143";
        String orderId = "1001";
        String formattedAmount = "2450.00";
        String currency = "LKR";
        String merchantSecret = "secret456";

        String actualHash = hashService.generateCheckoutHash(merchantId, orderId, formattedAmount, currency, merchantSecret);

        assertEquals("EFE64477BA400773370187C2800C5FDA", actualHash);
    }

    @Test
    @DisplayName("Notification md5sig generation and signature verification with known values")
    void testNotificationSignatureVerification() {
        String merchantId = "1211143";
        String orderId = "1001";
        String payhereAmount = "2450.00";
        String payhereCurrency = "LKR";
        String statusCode = "2";
        String merchantSecret = "secret456";

        // Fixed vector generated independently from the documented concatenation formula.
        String validSig = hashService.generateNotificationSignature(
                merchantId, orderId, payhereAmount, payhereCurrency, statusCode, merchantSecret
        );

        assertEquals("714A4BBC9AA60E7DF15028F819B05745", validSig);

        // PayHere sends the uppercase digest generated by the documented formula.
        assertTrue(hashService.verifyNotificationSignature(
                merchantId, orderId, payhereAmount, payhereCurrency, statusCode, merchantSecret, validSig
        ));
        assertFalse(hashService.verifyNotificationSignature(
                merchantId, orderId, payhereAmount, payhereCurrency, statusCode, merchantSecret, validSig.toLowerCase()
        ));
        assertFalse(hashService.verifyNotificationSignature(
                merchantId, orderId, payhereAmount, payhereCurrency, statusCode, merchantSecret, " " + validSig
        ));

        // Tampered amount fails
        assertFalse(hashService.verifyNotificationSignature(
                merchantId, orderId, "2400.00", payhereCurrency, statusCode, merchantSecret, validSig
        ));
        assertFalse(hashService.verifyNotificationSignature(
                merchantId, orderId, " 2450.00", payhereCurrency, statusCode, merchantSecret, validSig
        ));

        // Tampered orderId fails
        assertFalse(hashService.verifyNotificationSignature(
                merchantId, "9999", payhereAmount, payhereCurrency, statusCode, merchantSecret, validSig
        ));

        // Tampered status_code fails
        assertFalse(hashService.verifyNotificationSignature(
                merchantId, orderId, payhereAmount, payhereCurrency, "-2", merchantSecret, validSig
        ));

        // Tampered currency fails
        assertFalse(hashService.verifyNotificationSignature(
                merchantId, orderId, payhereAmount, "USD", statusCode, merchantSecret, validSig
        ));

        // Tampered merchantId fails
        assertFalse(hashService.verifyNotificationSignature(
                "wrong_merchant", orderId, payhereAmount, payhereCurrency, statusCode, merchantSecret, validSig
        ));

        // Wrong secret fails
        assertFalse(hashService.verifyNotificationSignature(
                merchantId, orderId, payhereAmount, payhereCurrency, statusCode, "different_secret", validSig
        ));

        // Null / blank signature fails
        assertFalse(hashService.verifyNotificationSignature(
                merchantId, orderId, payhereAmount, payhereCurrency, statusCode, merchantSecret, null
        ));
        assertFalse(hashService.verifyNotificationSignature(
                merchantId, orderId, payhereAmount, payhereCurrency, statusCode, merchantSecret, ""
        ));
    }

    @Test
    @DisplayName("PayHere notification values are verified exactly as received")
    void testGatewayDoesNotTrimSignedNotificationValues() {
        String signature = hashService.generateNotificationSignature(
                "1211143", "1001", "2450.00", "LKR", "2", "secret456"
        );
        PayHerePaymentGateway gateway = new PayHerePaymentGateway(
                new PayHereProperties("1211143", "secret456", "sandbox", "http://localhost:8080", "http://localhost:5173"),
                hashService
        );

        PaymentNotificationResult result = gateway.verifyAndParseNotification(Map.of(
                "merchant_id", "1211143",
                "order_id", "1001",
                "payhere_amount", " 2450.00",
                "payhere_currency", "LKR",
                "status_code", "2",
                "md5sig", signature
        ));

        assertFalse(result.signatureValid());
    }
}
